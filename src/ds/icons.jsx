/** Pixel icon. `size` 12 | 24 | 36 (default 24). Inherits `color`. */
export function Icon({ name, size = 24, title, className, style }) {
  const m = I[name];
  if (!m) return null;
  return (
    <svg className={'lm-icon' + (className ? ' ' + className : '')} width={size} height={size} viewBox="0 0 12 12"
      shapeRendering="crispEdges" fill="currentColor" aria-hidden={title ? undefined : true} role={title ? 'img' : undefined} style={style}>
      {title ? <title>{title}</title> : null}
      <path d={pixelPath(m)} />
    </svg>
  );
}

/** Realm emblem, 16×16 pixel mark. `size` 16 | 32 | 48. Color via `color` (defaults to currentColor). */
export function Emblem({ realm, size = 32, color, className, style }) {
  const m = E[realm];
  if (!m) return null;
  return (
    <svg className={'lm-emblem' + (className ? ' ' + className : '')} width={size} height={size} viewBox="0 0 16 16"
      shapeRendering="crispEdges" fill={color || 'currentColor'} aria-hidden="true" style={style}>
      <path d={pixelPath(m)} />
    </svg>
  );
}

/** Standalone SVG text for exporting a glyph as a file (fixed ink: no currentColor in <img>). */
export function svgString(m, ink, px = 2) {
  const n = m.length;
  return `<svg xmlns="http://www.w3.org/2000/svg" width="${n * px}" height="${n * px}" viewBox="0 0 ${n} ${n}" shape-rendering="crispEdges"><path fill="${ink}" d="${pixelPath(m)}"/></svg>`;
}
